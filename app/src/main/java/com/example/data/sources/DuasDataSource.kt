    fun filterDuas(category: String, query: String): List<DuaItem> {
        val catList = if (category == "all") allDuas else allDuas.filter { it.category == category }
        if (query.isBlank()) return catList
        val cleanQ = query.trim()
        return catList.filter {
            it.title.contains(cleanQ, ignoreCase = true) ||
                    it.text.contains(cleanQ, ignoreCase = true) ||
                    it.translationOrFadl.contains(cleanQ, ignoreCase = true) ||
                    it.reference.contains(cleanQ, ignoreCase = true)
        }
    }
