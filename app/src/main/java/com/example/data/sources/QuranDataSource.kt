    /**
     * Returns the Hizb (1..60) for any page in the 604-page Madinah Mushaf
     */
    fun getHizbForPage(page: Int): Int {
        val juz = getJuzForPage(page)
        val juzStart = if (juz == 1) 1 else 2 + (juz - 1) * 20
        val isSecondHalf = page >= (juzStart + 10)
        return (juz - 1) * 2 + (if (isSecondHalf) 2 else 1)
    }

    /**
     * Returns the active Surah for any page in the 604-page Madinah Mushaf
     */
    fun getSurahForPage(page: Int): Surah {
        val safePage = page.coerceIn(1, 604)
        return surahs.lastOrNull { it.pageNumber <= safePage } ?: surahs[0]
    }

