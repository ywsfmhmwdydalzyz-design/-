    /**
     * جلب آية اليوم تلقائياً بحسب تاريخ الجهاز اليومي بدون الحاجة للإنترنت
     */
    fun getTodayAyah(calendar: Calendar = Calendar.getInstance()): DailyAyah {
        val dayOfYear = calendar.get(Calendar.DAY_OF_YEAR)
        val year = calendar.get(Calendar.YEAR)
        val dayIndex = Math.abs(year * 365 + dayOfYear)
        return dailyAyahs[dayIndex % dailyAyahs.size]
    }

